<template>
  <div class="wrapper">
    <input
        type="text"
        :maxlength="API_KEY_LENGTH"
        placeholder="API Key"
        v-model="key"
    />
    <div class="api-links">
      Where to find API key?
      [<a href="/my/account.json" target="_blank">JSON</a>]
      [<a href="/my/account.html" target="_blank">HTML</a>]
    </div>
    <select
        v-if="api_key.length && activityOptions.length"
        v-model="activity_ids"
        :size="Math.min(activityOptions.length, 8)"
        multiple
    >
      <option v-for="o in activityOptions" :key="o.value" :value="o.value">{{ o.label }}</option>
    </select>
    <input
        v-if="api_key.length && activityOptions.length"
        type="submit"
        value="Save"
        @click="save"
    />
  </div>
</template>

<script setup lang="ts">
import {useConfigStore, useDataStore} from '../stores';
import {onBeforeMount, ref, watch, watchEffect} from 'vue';
import {storeToRefs} from 'pinia';

const configStore = useConfigStore();
const {load, save} = configStore;
const {api_key, activity_ids} = storeToRefs(configStore);

const API_KEY_LENGTH = 40;
const API_KEY_PATTERN = new RegExp(`^[0-9a-f]{${API_KEY_LENGTH}}$`);

// accept the key as soon as it is valid (40 lowercase hex chars, as generated by Redmine), not on blur
const key = ref('');
watch(api_key, (v) => {
  if (v) key.value = v;
}, {immediate: true});
watch(key, (v) => {
  const trimmed = v.trim();
  api_key.value = API_KEY_PATTERN.test(trimmed) ? trimmed : '';
});

const dataStore = useDataStore();
const {loadActivities} = dataStore;
const {activityOptions} = storeToRefs(dataStore);

onBeforeMount(async () => {
  await load();
});

watchEffect(async () => {
  if (api_key.value) {
    await loadActivities();
  }
});
</script>

<style scoped>
.wrapper {
  margin: 20px 0;
}
input[type=text], select {
  width: 100%;
  box-sizing: border-box;
}
.api-links {
  font-weight: bold;
}
</style>
